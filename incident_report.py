
from io import BytesIO
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table,
    TableStyle, KeepTogether
)


def build_incident_pdf(incident, recommendations):
    buffer = BytesIO()

    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title=f"CyberShield IR - Incident {incident.id}",
        author="CyberShield IR"
    )

    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(
        name="ReportSubtitle",
        parent=styles["Normal"],
        fontSize=9,
        textColor=colors.HexColor("#526174"),
        spaceAfter=12
    ))
    styles.add(ParagraphStyle(
        name="SectionHeading",
        parent=styles["Heading2"],
        textColor=colors.HexColor("#174A8B"),
        spaceBefore=12,
        spaceAfter=6
    ))
    styles.add(ParagraphStyle(
        name="SmallBody",
        parent=styles["BodyText"],
        fontSize=9,
        leading=13,
        alignment=TA_LEFT
    ))

    def para(value):
        return Paragraph(escape(str(value or "")), styles["SmallBody"])

    story = [
        Paragraph("CyberShield IR", styles["Title"]),
        Paragraph(
            "Cybersecurity Incident Response Report",
            styles["ReportSubtitle"]
        ),
        Paragraph(
            f"Incident #{incident.id}: {escape(incident.title)}",
            styles["Heading1"]
        ),
        Spacer(1, 5 * mm),
        Paragraph("Incident Details", styles["SectionHeading"])
    ]

    details = [
        [para("Incident Type"), para(incident.incident_type)],
        [para("Industry"), para(incident.industry)],
        [para("Severity"), para(incident.severity)],
        [para("Current Status"), para(incident.status)],
        [para("Reported At"), para(incident.created_at)],
        [para("Description"), para(incident.description)]
    ]

    table = Table(details, colWidths=[42 * mm, 125 * mm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#EEF3F8")),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#D4DCE5")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 7),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(table)

    story.append(Paragraph("Recommended Response Playbook",
                           styles["SectionHeading"]))
    story.append(Paragraph(
        "These are suggested actions. They are not proof that an action "
        "was performed. Follow your organization's approved procedures.",
        styles["SmallBody"]
    ))

    for number, recommendation in enumerate(recommendations, start=1):
        story.append(Paragraph(
            f"{number}. {escape(recommendation)}",
            styles["SmallBody"]
        ))
        story.append(Spacer(1, 3))

    story.append(Paragraph("Response History", styles["SectionHeading"]))

    if incident.actions:
        for action in sorted(incident.actions, key=lambda item: item.id):
            story.append(KeepTogether([
                Paragraph(
                    f"Entry #{action.id} — {escape(str(action.created_at))}",
                    styles["Heading4"]
                ),
                para(action.action),
                Spacer(1, 5)
            ]))
    else:
        story.append(para("No response actions have been recorded."))

    story.append(Spacer(1, 8 * mm))
    story.append(Paragraph(
        "Generated by CyberShield IR. Review this report for accuracy "
        "before using it for operational or compliance purposes.",
        styles["ReportSubtitle"]
    ))

    document.build(story)
    buffer.seek(0)
    return buffer
